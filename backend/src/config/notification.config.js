  [NOTIFICATION_TYPES.REVIEW_QUEUED]: [DELIVERY_CHANNELS.IN_APP],
  [NOTIFICATION_TYPES.REVIEW_STARTED]: [DELIVERY_CHANNELS.IN_APP],
  [NOTIFICATION_TYPES.REVIEW_COMPLETED]: [DELIVERY_CHANNELS.IN_APP, DELIVERY_CHANNELS.EMAIL],
  [NOTIFICATION_TYPES.REVIEW_FAILED]: [DELIVERY_CHANNELS.IN_APP, DELIVERY_CHANNELS.EMAIL],
  [NOTIFICATION_TYPES.CRITICAL_FINDING]: [DELIVERY_CHANNELS.IN_APP, DELIVERY_CHANNELS.EMAIL],
  [NOTIFICATION_TYPES.NEW_FINDING]: [DELIVERY_CHANNELS.IN_APP],
  [NOTIFICATION_TYPES.REPORT_READY]: [DELIVERY_CHANNELS.IN_APP, DELIVERY_CHANNELS.EMAIL],
  [NOTIFICATION_TYPES.REPORT_FAILED]: [DELIVERY_CHANNELS.IN_APP, DELIVERY_CHANNELS.EMAIL],
  [NOTIFICATION_TYPES.INVITATION_RECEIVED]: [DELIVERY_CHANNELS.IN_APP, DELIVERY_CHANNELS.EMAIL],
  [NOTIFICATION_TYPES.INVITATION_ACCEPTED]: [DELIVERY_CHANNELS.IN_APP],
