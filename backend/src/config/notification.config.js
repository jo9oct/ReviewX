  [NOTIFICATION_TYPES.SUBSCRIPTION_EXPIRING]: [DELIVERY_CHANNELS.IN_APP, DELIVERY_CHANNELS.EMAIL],
  [NOTIFICATION_TYPES.SUBSCRIPTION_EXPIRED]: [DELIVERY_CHANNELS.IN_APP, DELIVERY_CHANNELS.EMAIL],
  [NOTIFICATION_TYPES.PAYMENT_FAILED]: [DELIVERY_CHANNELS.IN_APP, DELIVERY_CHANNELS.EMAIL],
  [NOTIFICATION_TYPES.UPGRADE_REQUESTED]: [DELIVERY_CHANNELS.IN_APP],
  [NOTIFICATION_TYPES.UPGRADE_APPROVED]: [DELIVERY_CHANNELS.IN_APP, DELIVERY_CHANNELS.EMAIL],
  [NOTIFICATION_TYPES.USAGE_WARNING]: [DELIVERY_CHANNELS.IN_APP],
  [NOTIFICATION_TYPES.SECURITY_ALERT]: [DELIVERY_CHANNELS.IN_APP, DELIVERY_CHANNELS.EMAIL],
